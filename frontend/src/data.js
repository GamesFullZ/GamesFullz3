// Función para obtener juegos con paginación automática
export const getGamesPage = (page = 1, itemsPerPage = 12) => {
  const startIndex = (page - 1) * itemsPerPage;
  const endIndex = startIndex + itemsPerPage;
  const games = gamesData.slice(startIndex, endIndex);
  
  return {
    games,
    totalGames: gamesData.length,
    totalPages: Math.ceil(gamesData.length / itemsPerPage),
    currentPage: page,
    hasNextPage: endIndex < gamesData.length,
    hasPrevPage: page > 1
  };
};

// Función para obtener juegos destacados
export const getFeaturedGames = () => {
  return gamesData.filter(game => game.featured);
};

// Función para obtener juegos por categoría
export const getGamesByCategory = (category) => {
  return gamesData.filter(game => game.category === category);
};

// Función para buscar juegos
export const searchGames = (query) => {
  const lowercaseQuery = query.toLowerCase();
  return gamesData.filter(game => 
    game.title.toLowerCase().includes(lowercaseQuery) ||
    game.description.toLowerCase().includes(lowercaseQuery) ||
    game.tags.some(tag => tag.toLowerCase().includes(lowercaseQuery))
  );
};

// Función para obtener un juego por slug
export const getGameBySlug = (slug) => {
  return gamesData.find(game => game.slug === slug);
};

// Función para obtener juegos relacionados
export const getRelatedGames = (currentGameId, limit = 6) => {
  const currentGame = gamesData.find(game => game.id === currentGameId);
  if (!currentGame) return [];
  
  const related = gamesData
    .filter(game => 
      game.id !== currentGameId && 
      (game.category === currentGame.category || 
       game.tags.some(tag => currentGame.tags.includes(tag)))
    )
    .slice(0, limit);
    
  return related;
};